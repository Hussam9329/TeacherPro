// Used for both genders: never decided by a list or ending, so they stay for review.
const UNISEX_NAMES = words(`
وعد صباح جهاد نهاد فرات رضا براء ميلاد فيض اسلام عهد سرور جود نجاح ديار نورس
`);

const KEY_LETTERS: Record<string, string> = { "أ": "ا", "إ": "ا", "آ": "ا", "ة": "ه", "ى": "ي", "ی": "ي", "ک": "ك" };

/** Spelling-insensitive key for a first name. */
export function nameKey(name: string): string {
  let out = "";
  for (const ch of (name || "").trim()) {
    // Diacritics and tatweel.
    if ((ch >= "ً" && ch <= "ٟ") || ch === "ٰ" || ch === "ـ") continue;
    out += KEY_LETTERS[ch] ?? ch;
  }
  return out;
}

const FEMALE_KEYS = new Set(FEMALE_NAMES.map(nameKey));
const MALE_KEYS = new Set(MALE_NAMES.map(nameKey));
const UNISEX_KEYS = new Set(UNISEX_NAMES.map(nameKey));

function fromLists(key: string): ExtractedGender {
  const inFemale = FEMALE_KEYS.has(key);
  const inMale = MALE_KEYS.has(key);
  if (inFemale !== inMale) return inFemale ? FEMALE : MALE;
  return "";
}

/** «أنثى», «ذكر» or "" when nothing decides it. */
export function genderOf(firstName: string): ExtractedGender {
  const key = nameKey(firstName);
  if (!key) return "";
  if (UNISEX_KEYS.has(key)) return "";
  if (key.startsWith("عبد") || key.startsWith("ذو")) return MALE;
  const found = fromLists(key) || (key.startsWith("ال") ? fromLists(key.slice(2)) : "");
  if (found) return found;
  if (key.length >= 3 && (key.endsWith("ه") || key.endsWith("اء"))) return FEMALE;
  return "";
}
